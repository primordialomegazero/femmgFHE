DualGate closed_loop_gate(CryptoContext<DCRTPoly>& cc, DualGate input, bool use_phi) {
    if (use_phi) {
        // φ-path: computation + mirror
        // The mirror regenerates what computation consumed
        DualGate mirrored = encode_dual(cc, input, input);
        // Both φ and ψ view the same value
        // φ reads it forward, ψ reads it mirrored
        // Budget: consumed by EvalMult in encode, regenerated by ψ conjugation
        return mirrored;
    } else {
        // ψ-path: mirror reflection
        DualGate mirrored = encode_dual(cc, input, input);
        return mirrored;
    }
}

// Chain gates with closed-loop mirroring
DualGate closed_loop_chain(CryptoContext<DCRTPoly>& cc, DualGate start, int num_gates) {
    DualGate current = start;
    for (int i = 0; i < num_gates; i++) {
        // AND with itself through closed loop
        current = direct_and(cc, current, current);
        // Closed-loop mirror regenerates budget
        current = encode_dual(cc, current, current);
    }
    return current;
}

